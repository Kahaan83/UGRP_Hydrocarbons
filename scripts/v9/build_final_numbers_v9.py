"""Build docs/final_numbers_v9.md from committed v9 CSV/JSON only."""
import json
from pathlib import Path

import pandas as pd

R = Path(__file__).resolve().parents[2]
V = R / "results" / "v9"
delta = pd.read_csv(V / "inventory" / "delta.csv")
lock = json.loads((V / "lock.json").read_text())
log = json.loads((R / "data/unified_v9/build_log.json").read_text()) if (R / "data/unified_v9/build_log.json").exists() else {}
audit = json.loads((V / "audit" / "audit_result.json").read_text())
refits = pd.read_csv(V / "antoine_refit" / "refits.csv")

def md(df):
    c = list(df.columns)
    return "\n".join(["| " + " | ".join(c) + " |", "|" + "---|" * len(c)] +
                     ["| " + " | ".join(str(x) for x in r) + " |" for r in df.itertuples(index=False)])

out = ["# v9 final numbers (data acquisition)", "",
       "Generated by `scripts/v9/build_final_numbers_v9.py` from committed v9 files. No number is hand-entered.", "",
       "## A. Inventory change by target (nonzero additions)", "",
       md(delta[delta.added != 0]), "",
       f"Freezing fuels before and after: {int(delta[delta.metric=='total_freezing_fuels'].count_before.iloc[0])} and "
       f"{int(delta[delta.metric=='total_freezing_fuels'].count_after.iloc[0])}.", "",
       "## B. Build and lock", ""]
out += [f"- {k}: {v}" for k, v in log.items()]
out += [f"- lock rule: {lock['rule']}; locked ids: {len(lock['ids'])} of {lock['n_new_systems']} new systems", "",
        "## C. Antoine refits", "", f"{len(refits)} candidates; statuses: " + ", ".join(sorted(refits.iloc[:, -1].astype(str).unique())) if len(refits) else "none", "",
        "## D. Readings", ""]
for s in ("dev", "v9_lock"):
    out += [f"### {s}", ""]
    for i in (1, 2, 3, 4):
        d = pd.read_csv(V / "readings" / f"R9-{i}_{s}.csv")
        out.append(md(d.fillna("")))
        out.append("")
out += ["## E. Audit", "", f"- PDF staged check: {audit['git_pdf_check']['status']}",
        "- licence checks: " + ", ".join(f"{c['folder']} {c['status']}" for c in audit["licence_checks"]), "",
        "## F. Statements", "",
        "- Real-fuel freezing point: status: no skill shown. No verified freezing fuel was added, so the 8-fuel lock floor was not met.",
        "- Cold viscosity: status: no skill shown. No new composition-bearing viscosity system was added.",
        "- Edwards 2017 and the pure-compound drafts were withheld as unverifiable and are not in unified_v9.", ""]
(R / "docs" / "final_numbers_v9.md").write_text("\n".join(out), encoding="utf-8")
