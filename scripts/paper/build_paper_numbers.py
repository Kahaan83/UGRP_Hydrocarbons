"""Assemble docs/RESULTS_FOR_PAPER.md by copying sections verbatim from the per-version final-numbers docs.

No number is typed here. Each block is extracted by heading from a generated doc and labelled with its source.
Run: python scripts/paper/build_paper_numbers.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"


def section(path, heading):
    """Text under a heading (any level) up to the next heading of the same or higher level."""
    lines = (DOCS / path).read_text(encoding="utf-8").splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("#") and heading in l)
    level = len(lines[start]) - len(lines[start].lstrip("#"))
    out = []
    for l in lines[start + 1:]:
        m = re.match(r"(#+) ", l)
        if m and len(m.group(1)) <= level:
            break
        out.append(l)
    return "\n".join(out).strip()


BLOCKS = [
    ("1. Blend properties: headline results (v5, frozen BASE)", "final_numbers_v5.md", "A. Headline results per property"),
    ("2. Blend properties: margins and spec limits (v5)", "final_numbers_v5.md", "C. Margins and the spec limits"),
    ("3. Learned components that passed their gates (v5)", "final_numbers_v5.md", "D. Machine learning"),
    ("3b. Density pair model after v11b tuning (replaces the density ML numbers of section 3)", "final_numbers_v11.md", "C. Density adoption"),
    ("4. Inverse design (v5; model-level certification only)", "final_numbers_v5.md", "E. Inverse-design results"),
    ("5. Pure-compound models (v7, dev CV, optimistic)", "final_numbers_v7.md", "A. Pure compounds"),
    ("6. Blend alternatives tried in v7", "final_numbers_v7.md", "B. Blend properties"),
    ("7. Exploratory blend values from pure models (v7)", "final_numbers_v7.md", "C. Exploratory blend values"),
    ("8. ML-constant substitution, real-fuel freezing, designs (v8)", None, None),
    ("9. Data acquisition and re-evaluation (v9)", "final_numbers_v9.md", "A. Inventory change"),
    ("10. v9 build and lock", "final_numbers_v9.md", "B. Build and lock"),
    ("10b. v9 Antoine refits", "final_numbers_v9.md", "C. Antoine refits"),
    ("10c. v9 readings (dev and lock)", "final_numbers_v9.md", "D. Readings"),
    ("10d. v9 audit", "final_numbers_v9.md", "E. Audit"),
    ("11. v9 statements", "final_numbers_v9.md", "F. Statements"),
    ("11b. v11 and v11b tuning (viscosity not adopted)", "final_numbers_v11.md", "B. v11b nested tuning"),
    ("11c. v11c minor optimisations (xylene correction applied; it supersedes the S_F lab-liquidus MAEs 4.474 and 3.935 quoted in sections 1 and 2, and the viscosity hybrid supersedes the ML viscosity numbers of section 3 and the v11 viscosity statement of section 11b; others not adopted)", "final_numbers_v11c.md", "v11c final numbers"),
    ("12. v5 negative results (kept)", "final_numbers_v5.md", "F. Negative results"),
    ("13. Limitations (v5)", "final_numbers_v5.md", "G. Limitations"),
]


def main():
    out = ["# Results for the paper (generated; do not edit)", "",
           "Generated by `scripts/paper/build_paper_numbers.py`. Every block is copied verbatim from the named final-numbers document, "
           "which is itself generated from committed result files. Blend numbers (sections 1 to 4) are the frozen v5 BASE; "
           "pure-compound numbers (sections 5 to 7) are dev CV on tuning rows and are optimistic. "
           "The latest value of every quantity changed after v5 is in `docs/CURRENT_NUMBERS.md`. No laboratory validation exists; certification is model-level only. "
           "Where a model does not beat a constant the status is: no skill shown.", ""]
    for title, f, h in BLOCKS:
        out += [f"## {title}", ""]
        if f is None:
            body = (DOCS / "final_numbers_v8.md").read_text(encoding="utf-8").split("\n", 1)[1].strip()
            out += ["Source: `docs/final_numbers_v8.md`", "", body, ""]
        else:
            out += [f"Source: `docs/{f}`, heading \"{h}\"", "", section(f, h), ""]
    out += ["## 14. v10 PDF transcription (negative result)", "", "Source: `docs/final_numbers_v10.md`", "",
            (DOCS / "final_numbers_v10.md").read_text(encoding="utf-8").split("\n", 1)[1].strip(), ""]
    lock = (ROOT / "results/v7/lock/scored/NOT_SCORABLE.md").read_text(encoding="utf-8").split("\n", 1)[1].strip()
    out += ["## 15. v7 fresh flash lock", "", "Source: `results/v7/lock/scored/NOT_SCORABLE.md`", "", lock, ""]
    (DOCS / "RESULTS_FOR_PAPER.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/RESULTS_FOR_PAPER.md", len(out), "lines")


if __name__ == "__main__":
    main()
