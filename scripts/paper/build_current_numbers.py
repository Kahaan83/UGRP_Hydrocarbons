"""Generate docs/CURRENT_NUMBERS.md: the latest value of every quantity that changed after the v5 freeze, with what it supersedes.

Values are read from committed result files or copied from generated final-numbers docs; nothing is typed here.
Run: python scripts/paper/build_current_numbers.py
"""
import json, re
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "docs"
R = ROOT / "results"
f = lambda x, n=4: f"{x:.{n}f}"
J = lambda p: json.loads((ROOT / p).read_text())


def section(path, heading):
    lines = (D / path).read_text(encoding="utf-8").splitlines()
    s = next(i for i, l in enumerate(lines) if l.startswith("#") and heading in l)
    lv = len(lines[s]) - len(lines[s].lstrip("#"))
    out = []
    for l in lines[s + 1:]:
        m = re.match(r"(#+) ", l)
        if m and len(m.group(1)) <= lv:
            break
        out.append(l)
    return "\n".join(out).strip()


