#!/usr/bin/env python3
"""Ingest CRC 647 / AV-27-18 / AV-11-09 transcripts into data/processed/crc_fuels.csv.

Reads the already-parsed CSVs from data/raw/pour_point/ (generated by parse_crc_tables.py)
and re-emits them in the canonical long schema with:
  fuel_id, fuel_name, property, value, unit_std, T_C, method, source, tier, flag_oor

Range validation flags out-of-range values (flag_oor=True) rather than dropping them.
"""
import sys
import csv
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE / "data" / "processed" / "crc_fuels.csv"

SOURCES = [
    ("data/raw/pour_point/crc647_fuel_properties.csv", "crc647"),
    ("data/raw/pour_point/av2718_fuel_properties.csv", "av2718"),
    ("data/raw/pour_point/av1109_freezing_point.csv", "av1109"),
]

# Physical plausibility ranges; outside → flagged but kept
RANGES = {
    "pour_point_C":     (-100,  20),
    "freezing_point_C": (-100,  20),
    "cloud_point_C":    (-100,  30),
    "flash_point_C":    ( -30, 300),
    "viscosity_kin_cSt":(  0.1, 500),
    "density_kg_m3":    ( 650,  950),
}
# distillation_T*_C: jet fuel range roughly -50..350 °C
DISTIL_RANGE = (-50, 400)


def check_oor(prop, val):
    if prop in RANGES:
        lo, hi = RANGES[prop]
        return not (lo <= val <= hi)
    if prop.startswith("distillation_T") and prop.endswith("_C"):
        lo, hi = DISTIL_RANGE
        return not (lo <= val <= hi)
    return False


def main():
    rows = []
    stats = {}  # source → Counter per property

    for rel_path, source in SOURCES:
        p = HERE / rel_path
        if not p.exists():
            print(f"WARN: {p} not found — skipping", file=sys.stderr)
            continue
        df = pd.read_csv(p, dtype=str)
        per_prop = {}
        n_bad = 0
        for r in df.to_dict("records"):
            prop = str(r.get("property", "")).strip()
            raw_val = r.get("value_std", "")
            try:
                val = float(raw_val)
            except (TypeError, ValueError):
                n_bad += 1
                continue
            if not np.isfinite(val):
                n_bad += 1
                continue

            T_raw = r.get("T_C", "")
            try:
                T_C = float(T_raw) if T_raw not in ("", None) else np.nan
            except (TypeError, ValueError):
                T_C = np.nan

            oor = check_oor(prop, val)

            rows.append({
                "fuel_id":   str(r.get("fuel_code", "")).strip(),
                "fuel_name": str(r.get("fuel_name", "")).strip(),
                "property":  prop,
                "value":     val,
                "unit_std":  str(r.get("unit_std", "")).strip(),
                "T_C":       "" if np.isnan(T_C) else T_C,
                "method":    str(r.get("method", "")).strip(),
                "source":    source,
                "source_pdf":str(r.get("source_pdf", "")).strip(),
                "page":      str(r.get("page", "")).strip(),
                "value_raw": str(r.get("value_raw", "")).strip(),
                "tier":      "A",
                "flag_oor":  oor,
            })
            per_prop[prop] = per_prop.get(prop, 0) + 1

        stats[source] = (per_prop, n_bad)

    if not rows:
        print("ERROR: no rows produced — check source CSVs", file=sys.stderr)
        sys.exit(1)

    out_df = pd.DataFrame(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    out_df.to_csv(OUT, index=False)

    # --- summary ---------------------------------------------------------
    total = len(out_df)
    n_oor = int(out_df["flag_oor"].sum())
    print(f"\ncrc_fuels.csv: {total} rows, {n_oor} out-of-range flagged (kept)")
    for source, (per_prop, n_bad) in stats.items():
        n_src = sum(per_prop.values())
        print(f"\n  [{source}]  {n_src} rows ({n_bad} non-numeric skipped)")
        for prop in sorted(per_prop):
            sub = out_df[(out_df["source"] == source) & (out_df["property"] == prop)]
            v = sub["value"].astype(float)
            n = len(v)
            print(f"    {prop:<50s} n={n:4d}  min={v.min():.4g}  max={v.max():.4g}")

    # unique fuels per source
    print("\nUnique fuels per source:")
    for src in out_df["source"].unique():
        n_f = out_df[out_df["source"] == src]["fuel_id"].nunique()
        print(f"  {src}: {n_f} fuels")

    print(f"\nWrote: {OUT}")
    return out_df, stats


if __name__ == "__main__":
    main()
